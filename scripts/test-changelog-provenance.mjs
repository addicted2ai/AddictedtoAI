#!/usr/bin/env node
// Proof that scripts/check-changelog-provenance.mjs can actually go red.
// Run from the repository root:
//
//   node scripts/test-changelog-provenance.mjs
//
// WHY. `prompts/shared/every-run.md`: "If you add an assertion, prove it can
// fail before trusting it: feed it something wrong and confirm it complains.
// This project has shipped green checks that could not go red, and one that
// passed while measuring the wrong build entirely."
//
// Each case below builds a sandbox under the OS temp directory, plants one
// defect, and asserts the checker exits non-zero AND says something
// recognisable about that specific defect. The second half matters: a check
// that fails for an unrelated reason on a mutated tree has not been shown to
// detect the mutation.
//
// TWO KINDS OF SANDBOX, because the three assertions need different records.
//
//   `realSandbox()`  copies this repository's own CHANGELOG.md, policy.yml
//                    and scripts/, and is used for the per-entry assertions
//                    (Dispatch shape, Agent resolution) -- planted into the
//                    round the loop actually just wrote.
//
//   `syntheticTree()` generates a record of 204 rounds, so the composition
//                    assertion's window (the newest 20) sits entirely at or
//                    above the round it is armed from. That state cannot be
//                    reached by editing the real changelog: the real newest
//                    round IS the arming round, so its window necessarily
//                    reaches back below the seam and the assertion is
//                    correctly still holding fire. Generating the record is
//                    the only way to watch the armed path go red -- and to
//                    watch it go GREEN, which the second control does.
//
// The sandboxes are copies. Nothing here writes to the working tree.

import fs from "fs";
import os from "os";
import path from "path";
import { execFileSync } from "child_process";

const root = process.cwd();
const checker = path.join(root, "scripts", "check-changelog-provenance.mjs");

// Everything scripts/check-changelog-provenance.mjs reads when pointed at a
// root other than the working directory. app/lib/build-log.js is absent on
// purpose: the checker skips its cross-check against a sandbox root (that
// module reads process.cwd()) and says so rather than passing silently.
const NEEDED = ["CHANGELOG.md", "policy.yml", "scripts"];

// The seam scripts/check-changelog-provenance.mjs enforces from. Read out of
// the checker rather than retyped, so this test cannot drift from it.
const ENFORCED_FROM = Number(
  (fs.readFileSync(checker, "utf8").match(/^const ENFORCED_FROM = (\d+);$/m) ||
    [])[1]
);
if (!Number.isInteger(ENFORCED_FROM)) {
  console.log(
    "FAIL  could not read ENFORCED_FROM out of scripts/check-changelog-provenance.mjs -- " +
      "this test's premise about the checker is stale, which is a failure, not a skip"
  );
  process.exit(1);
}

function realSandbox(name) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `cl-prov-${name}-`));
  for (const entry of NEEDED) {
    fs.cpSync(path.join(root, entry), path.join(dir, entry), { recursive: true });
  }
  return dir;
}

// A generated record: `total` rounds, newest first, each carrying Track,
// Agent and (from ENFORCED_FROM up) Dispatch. `tracksNewest` supplies the
// tracks for the newest rounds, newest first; anything past it repeats a
// filler cycle that includes every track, so only the newest window is under
// test.
function syntheticChangelog(total, tracksNewest) {
  const filler = ["scout", "maintain", "author", "build", "audit", "meta"];
  const parts = [
    "# Changelog & Loop Log\n",
    "Generated by scripts/test-changelog-provenance.mjs. Not a real record.\n",
    "## Log\n",
  ];
  for (let i = 0; i < total; i++) {
    const number = total - i; // app/lib/build-log.js's own formula
    const track = tracksNewest[i] ?? filler[i % filler.length];
    parts.push(`### 2026-08-24`);
    parts.push(`Synthetic round ${number}.`);
    parts.push("");
    parts.push("- Origin: delegated");
    parts.push(`- Track: ${track}`);
    parts.push("- Agent: claude-opus-5 (orchestrating model)");
    if (number >= ENFORCED_FROM) {
      parts.push("- Dispatch: dispatcher — quota: synthetic");
    }
    parts.push("- Guardrails: none, this is a fixture");
    parts.push("- Result: not measured");
    parts.push("");
  }
  return parts.join("\n");
}

function syntheticTree(name, tracksNewest, total = ENFORCED_FROM + 19) {
  const dir = realSandbox(name);
  fs.writeFileSync(
    path.join(dir, "CHANGELOG.md"),
    syntheticChangelog(total, tracksNewest)
  );
  return dir;
}

function edit(dir, file, from, to) {
  const p = path.join(dir, file);
  const text = fs.readFileSync(p, "utf8");
  if (!text.includes(from)) {
    throw new Error(
      `test setup: ${file} in the sandbox does not contain ${JSON.stringify(
        from.slice(0, 70)
      )} -- this test's own premise about the tree is stale, which is a failure, not a skip`
    );
  }
  fs.writeFileSync(p, text.replace(from, to));
}

// Replace the Dispatch bullet of the newest entry, whatever it currently
// says. The real changelog's newest entry is this round's own.
function replaceNewestBullet(dir, field, replacement) {
  const p = path.join(dir, "CHANGELOG.md");
  const text = fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n");
  const re = new RegExp(`^- ${field}:.*(?:\\n[ \\t]+\\S.*)*$`, "m");
  if (!re.test(text)) {
    throw new Error(
      `test setup: no '- ${field}:' bullet found in the sandbox CHANGELOG.md -- ` +
        "this test's premise about the record is stale"
    );
  }
  fs.writeFileSync(p, text.replace(re, replacement));
}

function run(dir) {
  try {
    const out = execFileSync(process.execPath, [checker, dir], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
    return { code: 0, out };
  } catch (error) {
    return { code: error.status ?? 1, out: `${error.stdout || ""}${error.stderr || ""}` };
  }
}

// --- controls ----------------------------------------------------------------
//
// Without these, every case below could be "failing" because the sandbox
// itself is broken, and the composition assertion could be one that fires on
// everything.

const CONTROLS = [
  {
    name: "control-real",
    what: "an unmutated copy of this repository's own record passes",
    make: () => realSandbox("control-real"),
  },
  {
    name: "control-healthy-composition",
    what:
      "a generated record whose newest 20 rounds include scout and maintain passes " +
      "on the ARMED composition path",
    make: () =>
      syntheticTree("control-healthy", [
        "meta", "build", "scout", "build", "author", "maintain", "build", "meta",
        "audit", "build", "scout", "author", "build", "maintain", "meta", "build",
        "author", "audit", "build", "scout",
      ]),
    // The armed path must actually have been reached, not skipped -- a
    // control that passes because the assertion never ran proves nothing.
    expect: /composition: every track policy\.yml weights >= 20/,
  },
];

let failures = 0;
for (const control of CONTROLS) {
  let dir;
  try {
    dir = control.make();
    const result = run(dir);
    if (result.code !== 0) {
      console.log(`FAIL  ${control.name}: ${control.what} -- it did not`);
      console.log(result.out.split("\n").slice(-14).join("\n"));
      failures++;
    } else if (control.expect && !control.expect.test(result.out)) {
      console.log(
        `FAIL  ${control.name}: passed, but not by the path under test -- expected ` +
          `output matching ${control.expect}`
      );
      failures++;
    } else {
      console.log(`ok    ${control.name} -- ${control.what}`);
    }
  } catch (error) {
    console.log(`FAIL  ${control.name}: ${error.message}`);
    failures++;
  } finally {
    if (dir) fs.rmSync(dir, { recursive: true, force: true });
  }
}

// --- planted defects ---------------------------------------------------------

const CASES = [
  {
    name: "dispatch-absent",
    what: "a round from the enforced era ships with no Dispatch field at all",
    expect: /no '- Dispatch:' field/,
    make: () => {
      const dir = realSandbox("dispatch-absent");
      replaceNewestBullet(dir, "Dispatch", "- Note: nothing to see here");
      return dir;
    },
  },
  {
    name: "dispatch-empty",
    what: "the Dispatch field is present but says nothing",
    expect: /is present but empty/,
    make: () => {
      const dir = realSandbox("dispatch-empty");
      replaceNewestBullet(dir, "Dispatch", "- Dispatch:");
      return dir;
    },
  },
  {
    name: "dispatch-verdict-without-reason",
    what: "the round says it was forced but does not say why -- the whole point of the field",
    expect: /not one of the two legitimate shapes/,
    make: () => {
      const dir = realSandbox("dispatch-verdict-only");
      replaceNewestBullet(dir, "Dispatch", "- Dispatch: forced");
      return dir;
    },
  },
  {
    name: "dispatch-unknown-verdict",
    what: "a third verdict is invented rather than declaring dispatcher or forced",
    expect: /not one of the two legitimate shapes/,
    make: () => {
      const dir = realSandbox("dispatch-unknown");
      replaceNewestBullet(dir, "Dispatch", "- Dispatch: probably fine — it seemed right");
      return dir;
    },
  },
  {
    name: "agent-unregistered",
    what: "a round names an Agent that resolves to no runner in scripts/runners.yml",
    expect: /does not resolve to a runner in scripts\/runners\.yml/,
    make: () => {
      const dir = realSandbox("agent-unregistered");
      replaceNewestBullet(dir, "Agent", "- Agent: some-model-nobody-registered (a subagent)");
      return dir;
    },
  },
  {
    name: "agent-absent",
    what: "a round from the enforced era names nothing that ran it",
    expect: /no '- Agent:' field/,
    make: () => {
      const dir = realSandbox("agent-absent");
      replaceNewestBullet(dir, "Agent", "- Note: it ran somehow");
      return dir;
    },
  },
  {
    name: "runner-deregistered",
    what: "the runner a shipped round named is deleted from scripts/runners.yml",
    expect: /does not resolve to a runner in scripts\/runners\.yml/,
    make: () => {
      const dir = realSandbox("runner-deregistered");
      edit(dir, "scripts/runners.yml", "    model: claude-opus-5\n", "    model: claude-opus-6\n");
      return dir;
    },
  },
  {
    name: "composition-scout-starved",
    what:
      "the newest 20 rounds of an armed window contain no scout round, though " +
      "policy.yml weights scout at 30",
    expect: /composition: scout \(policy weight 30\) shipped 0/,
    make: () =>
      syntheticTree("composition-scout", [
        "meta", "build", "build", "build", "meta", "author", "meta", "build",
        "build", "build", "meta", "meta", "meta", "build", "meta", "build",
        "meta", "meta", "author", "maintain",
      ]),
  },
  {
    name: "composition-both-starved",
    what: "neither heavy track shipped across an armed window -- the state found on 2026-08-24",
    expect: /scout \(policy weight 30\) shipped 0; maintain \(policy weight 25\) shipped 0/,
    make: () =>
      syntheticTree("composition-both", [
        "meta", "build", "build", "build", "meta", "author", "meta", "build",
        "build", "build", "meta", "meta", "meta", "build", "meta", "build",
        "meta", "meta", "author", "audit",
      ]),
  },
  {
    name: "composition-window-unreadable",
    what: "scripts/dispatch.mjs stops declaring the window this assertion reads",
    expect: /no longer declares `const WINDOW/,
    make: () => {
      const dir = realSandbox("window-unreadable");
      edit(dir, "scripts/dispatch.mjs", "const WINDOW = 20;", "const WINDOW = 10 * 2;");
      return dir;
    },
  },
  {
    name: "heavy-tracks-vanish",
    what: "policy.yml stops weighting any track at 20 or above, leaving nothing to assert",
    expect: /has nothing to assert, which must not read as a pass/,
    make: () => {
      const dir = realSandbox("heavy-gone");
      edit(dir, "policy.yml", "  scout:\n    weight: 30", "  scout:\n    weight: 3");
      edit(dir, "policy.yml", "  maintain:\n    weight: 25", "  maintain:\n    weight: 2");
      return dir;
    },
  },
  {
    name: "enforced-era-empty",
    what: "the record holds no round the checks apply to, so they assert nothing",
    expect: /nothing to assert, which must not read as a pass/,
    make: () => syntheticTree("era-empty", [], ENFORCED_FROM - 1),
  },
];

for (const testCase of CASES) {
  let dir;
  try {
    dir = testCase.make();
    const result = run(dir);
    if (result.code === 0) {
      console.log(`FAIL  ${testCase.name}: ${testCase.what} -- checker still passed`);
      failures++;
    } else if (!testCase.expect.test(result.out)) {
      console.log(
        `FAIL  ${testCase.name}: ${testCase.what} -- checker failed, but not about this: ` +
          `expected output matching ${testCase.expect}`
      );
      console.log(result.out.split("\n").filter((l) => /^FAIL/.test(l)).slice(0, 4).join("\n"));
      failures++;
    } else {
      console.log(`ok    ${testCase.name} -- ${testCase.what}: caught`);
    }
  } catch (error) {
    console.log(`FAIL  ${testCase.name}: ${error.message}`);
    failures++;
  } finally {
    if (dir) fs.rmSync(dir, { recursive: true, force: true });
  }
}

console.log();
console.log(
  `changelog-provenance check proved able to fail on ${CASES.length - failures}/${
    CASES.length
  } planted defect(s), with ${CONTROLS.length} control(s)`
);
console.log(
  "honest limit: this proves the checker detects these planted defects on these fixtures. " +
    "It says nothing about a round that writes a truthful-looking Dispatch reason which is " +
    "not the reason -- no check in this repository can read intent, and this one does not " +
    "claim to."
);

if (failures > 0) {
  console.log(`\n${failures} problem(s)`);
  process.exit(1);
}
process.exit(0);
